#!/usr/bin/env node
// Build the recorded-path exemplar (ADR 0010, docs/contracts/record.md) from the reviewed non-answer exemplar.
//
// The recorded path is the one aftergrid does not run: the Operator's harness executes the SQL with its own tool
// and `aftergrid record` writes down what it ran and what came back. A fixture for it therefore cannot be built
// by `scripts/fixture-tool.mjs build`, which runs the SQL itself. This script stands in for the harness: it runs
// the SAME SQL through DuckDB once, outside the Finding, over the source exemplar's retained extract, and then
// writes the result, the Check transcripts and the manifest exactly as `aftergrid record` would have.
//
// Everything is deterministic: fixed timestamps, no randomness, no clock. Regenerate with
//   node scripts/build-recorded-fixture.mjs
// and never hand-edit the generated directory.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDocument } from "yaml";
import { safePath, validateResult } from "./fixture-safety.mjs";
import { digestOf } from "./lib/validate-finding.mjs";
import { openRetainedDatabase, runSelect, checkOutcome } from "./lib/sql-runner.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FINDINGS = join(REPO, "fixtures/instance/analytics/findings");
const SRC = join(FINDINGS, "2026-09-15-price-change-cancellations");
const DST = join(FINDINGS, "2026-09-16-price-change-cancellations-recorded");

const FINDING_ID = "fnd_9d4h6m2s8xkp";
const RAN_AT = "2026-09-16T09:12:44Z";
const RECORDED_AT = "2026-09-16T09:14:02Z";
const GENERATED_AT = "2026-09-16T10:00:00Z";
const TOOL = "duckdb cli";

const sha = (buf) => createHash("sha256").update(buf).digest("hex");
const H = (buf) => ({ algorithm: "sha256", value: sha(buf) });

const HEADER = `# Exemplar: the recorded data path (ADR 0010, docs/contracts/record.md). Same Question, same SQL and the same
# honest insufficient-data answer as 2026-09-15-price-change-cancellations, produced the other way round: the
# Operator's own tool ran every query and every Check against the source, and aftergrid wrote down what it ran.
# Nothing was captured, so snapshot.inputs is empty and snapshot.guarantees is exactly [artifact_replay]:
# the saved bytes replay, and \`aftergrid check --mode rerun\` refuses this Finding with rerun_unavailable.
# Check outcomes here are agent-reported (checks[].reported_by) and each pass carries the tool output it rests on.
# Generated by scripts/build-recorded-fixture.mjs, which runs the SAME SQL through DuckDB once, outside this
# directory, in place of the harness. Regenerate, never hand-edit.
`;

/** One transcript of what the tool printed when it ran a Check, as the Operator would have saved it. */
function transcript(check, params, names, rows) {
  const p = Object.entries(params).map(([k, v]) => `${k}=${v}`).join(", ");
  const cell = (v) => (v === null ? "" : String(v));
  return [
    `# ${check.path}`,
    `# run ${RAN_AT} by ${TOOL}, outside aftergrid`,
    `# parameters: ${p}`,
    names.join("|"),
    ...rows.map((r) => names.map((n) => cell(r[n])).join("|")),
    "",
  ].join("\n");
}

const coerce = (v, type) => {
  if (v === null) return null;
  if (type === "integer") return Number(v);
  if (type === "boolean") return v;
  return String(v);
};

const MEMO_EDITS = [
  [
    "- No subscription is counted twice (Check unique_subscriptions).",
    "- No subscription is counted twice (Check unique_subscriptions). Every Check below was run by the Operator's own tool and reported to aftergrid, which did not run them; the tool's output for each is saved beside this Finding.",
  ],
  [
    "- Data: a retained copy of all subscriptions through the fourteenth of September. The numbers can be replayed from the saved results and rerun against the retained copy.",
    "- Data: the Operator's own tool read the subscriptions through the fourteenth of September, directly from the source. No copy was kept, so these numbers can be replayed exactly as saved, and the queries cannot be rerun against anything here.",
  ],
  [
    "- Retained input: inputs/subscriptions.csv, hash in the manifest.",
    "- Retained input: none. What was run is in the manifest: the query text, the parameters, the tool that ran it, and the hash of everything it produced.\n- Check evidence: the tool's output for each Check, under checks/evidence/, hashes in the manifest.",
  ],
  [
    "- Method review: recorded by the exemplar author. No human has approved this Finding for publication; it is a draft.",
    "- Method review: recorded by the exemplar author. No human has approved this Finding for publication; it is a draft.\n- What none of this establishes: the Checks were reported, not executed here, so a passing Check is the tool's word and the guardrail that watches shell commands never saw whatever the tool did.",
  ],
];

function replaceOnce(text, from, to) {
  const at = text.indexOf(from);
  if (at < 0 || text.indexOf(from, at + 1) >= 0) throw new Error(`expected exactly one occurrence of ${JSON.stringify(from.slice(0, 50))}`);
  return text.slice(0, at) + to + text.slice(at + from.length);
}

const doc = parseDocument(readFileSync(join(SRC, "manifest.yaml"), "utf8"));
const src = doc.toJS();

rmSync(DST, { recursive: true, force: true });
mkdirSync(join(DST, "queries"), { recursive: true });
mkdirSync(join(DST, "checks", "evidence"), { recursive: true });
mkdirSync(join(DST, "results"), { recursive: true });
for (const q of src.queries) cpSync(join(SRC, q.path), join(DST, q.path));
for (const c of src.checks) cpSync(join(SRC, c.path), join(DST, c.path));

// The memo, with every sentence that promised a retained copy or a rerun replaced by what actually happened.
let memo = readFileSync(join(SRC, "memo.md"), "utf8").replace(/^finding: fnd_[a-z0-9]{12}$/m, `finding: ${FINDING_ID}`);
for (const [from, to] of MEMO_EDITS) memo = replaceOnce(memo, from, to);
writeFileSync(join(DST, "memo.md"), memo);

// The harness's turn: the same SQL, through DuckDB, over the source exemplar's extract, outside this Finding.
const { c, close } = await openRetainedDatabase(SRC, src.snapshot.inputs);
try {
  for (const [i, ex] of src.executions.entries()) {
    const query = src.queries.find((q) => q.id === ex.query_id);
    const res = src.results.find((r) => r.id === ex.result_id);
    const { names, rows } = await runSelect(c, readFileSync(join(DST, query.path), "utf8"), ex.parameters);
    const declared = res.columns.map((x) => x.name);
    if (JSON.stringify(names) !== JSON.stringify(declared)) throw new Error(`${ex.id}: columns ${names} do not match declared ${declared}`);
    const out = {
      result_id: res.id, execution_id: ex.id, row_key: res.row_key, columns: declared,
      rows: rows.map((row) => Object.fromEntries(res.columns.map((col) => [col.name, coerce(row[col.name], col.type)]))),
    };
    const bytes = Buffer.from(JSON.stringify(out, null, 2) + "\n", "utf8");
    validateResult(out, { ...res, row_count: out.rows.length });
    writeFileSync(safePath(DST, res.path), bytes);
    const ri = src.results.findIndex((r) => r.id === res.id);
    const sqlBytes = readFileSync(safePath(DST, query.path));
    doc.setIn(["queries", src.queries.indexOf(query), "content_hash"], H(sqlBytes));
    doc.setIn(["executions", i, "sql_hash"], H(sqlBytes));
    doc.setIn(["executions", i, "input_ids"], []);
    doc.setIn(["executions", i, "result_hash"], H(bytes));
    doc.setIn(["executions", i, "mode"], "recorded");
    doc.setIn(["executions", i, "executed_by"], { kind: "harness", tool: TOOL, recorded_at: RECORDED_AT });
    doc.setIn(["executions", i, "executed_at"], RAN_AT);
    doc.deleteIn(["executions", i, "adapter"]);
    doc.deleteIn(["executions", i, "engine_version"]);
    doc.setIn(["results", ri, "content_hash"], H(bytes));
    doc.setIn(["results", ri, "row_count"], out.rows.length);
    console.log(`recorded ${ex.id}: ${out.rows.length} row(s)`);
  }
  for (const [i, ck] of src.checks.entries()) {
    const ex = ck.execution_id ? src.executions.find((e) => e.id === ck.execution_id) : src.executions[0];
    const sql = readFileSync(safePath(DST, ck.path), "utf8");
    const { names, rows } = await runSelect(c, sql, ex.parameters);
    const { outcome } = checkOutcome(names, rows, ck.path);
    doc.setIn(["checks", i, "content_hash"], H(Buffer.from(sql, "utf8")));
    doc.setIn(["checks", i, "outcome"], outcome);
    doc.setIn(["checks", i, "executed_at"], RAN_AT);
    const reported = { kind: "harness", tool: TOOL, reported_at: RECORDED_AT };
    // A pass reported by the harness must carry the artifact it rests on; a fail may, and does here. The
    // falsifier is left without one deliberately: it declared itself not evaluable, and there is nothing to show.
    if (outcome !== "not_run") {
      const rel = `checks/evidence/${ck.id}.txt`;
      const bytes = Buffer.from(transcript(ck, ex.parameters, names, rows), "utf8");
      writeFileSync(safePath(DST, rel), bytes);
      reported.evidence = { path: rel, content_hash: H(bytes) };
    }
    doc.setIn(["checks", i, "reported_by"], reported);
    console.log(`reported ${ck.id}: ${outcome}`);
  }
} finally { close(); }

doc.setIn(["finding", "id"], FINDING_ID);
doc.setIn(["finding", "slug"], "price-change-cancellations-recorded");
doc.setIn(["finding", "generated_at"], GENERATED_AT);
doc.setIn(["finding", "canonical_location"], "loop-example/analytics/analytics/findings/2026-09-16-price-change-cancellations-recorded");
doc.setIn(["snapshot", "id"], "snap_recorded_subscriptions");
doc.setIn(["snapshot", "inputs"], []);
doc.setIn(["snapshot", "guarantees"], ["artifact_replay"]);
doc.setIn(["coverage", "description"], "Cancellations from the day of the price change through September 14, 2026, read from the source by the Operator's own tool. Nothing was retained, so these numbers can be replayed exactly as saved and cannot be recomputed here.");
doc.setIn(["reviews", 0, "reviewer"], "fixture: hand review by the exemplar author (CrimsonLotus, claude-fable-5-1)");
doc.setIn(["reviews", 0, "date"], "2026-09-16");
doc.setIn(["reviews", 0, "non_blocking"], [
  "The weekly cancellation rate definition is proposed, so no rate is shown; only counts.",
  "Every Check outcome here was reported by the Operator's tool. aftergrid executed nothing, and the Finding says so in the manifest and on the rendered page.",
]);
doc.commentBefore = null;

const digest = digestOf(doc.toJS(), DST);
doc.setIn(["reviews", 0, "content_digest"], digest);
doc.setIn(["content_digest"], digest);
writeFileSync(join(DST, "manifest.yaml"), HEADER + doc.toString({ lineWidth: 0 }));
console.log(`wrote ${DST}; digest ${digest.value}`);
